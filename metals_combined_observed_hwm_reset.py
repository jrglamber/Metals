"""Authenticated reset for the combined observed P&L peak; reporting only."""
from __future__ import annotations

import hmac
from datetime import datetime, timezone
from typing import Any, Dict, Optional

from fastapi import Header, HTTPException, Request

import metals_combined_observed_hwm as observed_hwm
import metals_live_open_pnl_display as combined

VERSION = "metals_combined_observed_hwm_reset_v1_2026_11_24"
PREVIEW_ROUTE = "/api/live-metals-combined-peak-reset/preview"
RESET_ROUTE = "/api/live-metals-combined-peak-reset/reset"


def _timestamp(value: Any) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError("Missing combined broker observation timestamp")
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        raise ValueError("Naive combined broker observation timestamp")
    return parsed.astimezone(timezone.utc).isoformat()


def _stored(core: Any) -> Dict[str, Any]:
    with core.get_conn() as conn:
        conn.execute(
            """CREATE TABLE IF NOT EXISTS metals_combined_live_pnl_observed_hwm (
                 id INTEGER PRIMARY KEY, started_at_utc TEXT NOT NULL,
                 high_water_gbp REAL NOT NULL, high_water_at_utc TEXT NOT NULL)"""
        )
        row = conn.execute(
            """SELECT started_at_utc, high_water_gbp, high_water_at_utc
               FROM metals_combined_live_pnl_observed_hwm WHERE id=1"""
        ).fetchone()
        conn.commit()
    if row is None:
        return {"started_at_utc": None, "high_water_gbp": None, "high_water_at_utc": None}
    return {k: row[k] for k in ("started_at_utc", "high_water_gbp", "high_water_at_utc")}


def _fresh_proof() -> Dict[str, Any]:
    from metals_dashboard_clean_entrypoint import live_metals_open_positions
    payload = live_metals_open_positions()
    proof = combined.reconcile(payload)
    observed_at = _timestamp(proof.get("observed_at_utc"))
    return {
        "ok": True, "scope": combined.SCOPE,
        "current_gbp": float(proof["open_pnl_gbp"]),
        "open_count": int(proof["open_count"]),
        "xau_count": int(proof["xau_count"]),
        "xag_short_count": int(proof["xag_short_count"]),
        "observed_at_utc": observed_at,
        "broker_reconciled": True,
    }


def _preview(core: Any) -> Dict[str, Any]:
    try:
        proof = _fresh_proof()
        state = _stored(core)
        return {
            "ok": True, "allowed": True, "baseline": proof,
            "previous_peak_gbp": state.get("high_water_gbp"),
            "previous_peak_at_utc": state.get("high_water_at_utc"),
            "scope": "REPORTING_ONLY_COMBINED_LIVE_OPEN_PNL",
            "trading_state_affected": False, "version": VERSION,
        }
    except Exception as exc:
        return {
            "ok": True, "allowed": False, "baseline": None,
            "blockers": [f"verified_combined_broker_snapshot_unavailable:{type(exc).__name__}"],
            "scope": "REPORTING_ONLY_COMBINED_LIVE_OPEN_PNL",
            "trading_state_affected": False, "version": VERSION,
        }


def _apply(core: Any, proof: Dict[str, Any]) -> Dict[str, Any]:
    pnl = float(proof["current_gbp"])
    baseline = max(0.0, pnl)
    observed_at = _timestamp(proof["observed_at_utc"])
    with core.get_conn() as conn:
        conn.execute(
            """CREATE TABLE IF NOT EXISTS metals_combined_live_pnl_observed_hwm (
                 id INTEGER PRIMARY KEY, started_at_utc TEXT NOT NULL,
                 high_water_gbp REAL NOT NULL, high_water_at_utc TEXT NOT NULL)"""
        )
        conn.execute(
            """INSERT INTO metals_combined_live_pnl_observed_hwm
               (id, started_at_utc, high_water_gbp, high_water_at_utc)
               VALUES (1, ?, ?, ?) ON CONFLICT(id) DO NOTHING""",
            (observed_at, baseline, observed_at),
        )
        previous = conn.execute(
            """SELECT high_water_gbp FROM metals_combined_live_pnl_observed_hwm
               WHERE id=1"""
        ).fetchone()
        previous_gbp = float(previous["high_water_gbp"] or 0.0) if previous else 0.0
        conn.execute(
            """UPDATE metals_combined_live_pnl_observed_hwm
               SET started_at_utc=?, high_water_gbp=?, high_water_at_utc=?
               WHERE id=1""",
            (observed_at, baseline, observed_at),
        )
        conn.execute(
            """CREATE TABLE IF NOT EXISTS metals_combined_live_pnl_observed_hwm_resets (
                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 reset_at_utc TEXT NOT NULL, previous_peak_gbp REAL NOT NULL,
                 new_peak_gbp REAL NOT NULL, current_open_pnl_gbp REAL NOT NULL,
                 open_count INTEGER NOT NULL, xau_count INTEGER NOT NULL,
                 xag_short_count INTEGER NOT NULL)"""
        )
        conn.execute(
            """INSERT INTO metals_combined_live_pnl_observed_hwm_resets
               (reset_at_utc, previous_peak_gbp, new_peak_gbp,
                current_open_pnl_gbp, open_count, xau_count, xag_short_count)
               VALUES (?,?,?,?,?,?,?)""",
            (observed_at, previous_gbp, baseline, pnl, proof["open_count"],
             proof["xau_count"], proof["xag_short_count"]),
        )
        conn.commit()
    return {
        "ok": True, "status": "COMBINED_OBSERVED_PEAK_RESET",
        "previous_peak_gbp": previous_gbp, "new_peak_gbp": baseline,
        "current_open_pnl_gbp": pnl, "observed_at_utc": observed_at,
        "open_count": proof["open_count"], "xau_count": proof["xau_count"],
        "xag_short_count": proof["xag_short_count"],
        "trading_state_affected": False, "harvest_cycles_affected": False,
        "open_positions_changed": False,
    }


def install(core: Any, app: Any) -> Dict[str, Any]:
    def preview() -> Dict[str, Any]:
        return _preview(core)

    async def reset(request: Request, x_webhook_secret: Optional[str] = Header(default=None)) -> Dict[str, Any]:
        expected = str(getattr(core, "WEBHOOK_SECRET", "") or "")
        if not expected or not x_webhook_secret or not hmac.compare_digest(str(x_webhook_secret), expected):
            raise HTTPException(status_code=401, detail="Invalid WEBHOOK_SECRET")
        try:
            body = await request.json()
        except Exception:
            raise HTTPException(status_code=400, detail="Invalid JSON")
        if (not isinstance(body, dict)
                or body.get("confirm") != "RESET_COMBINED_OBSERVED_PEAK"
                or body.get("acknowledge_reporting_only") is not True):
            raise HTTPException(status_code=400, detail="Explicit reporting-only reset confirmation required")
        proof = _fresh_proof()
        return _apply(core, proof)

    app.add_api_route(PREVIEW_ROUTE, preview, methods=["GET"], include_in_schema=False)
    app.add_api_route(RESET_ROUTE, reset, methods=["POST"], include_in_schema=False)
    for path in (PREVIEW_ROUTE, RESET_ROUTE):
        routes = [route for route in app.router.routes if getattr(route, "path", "") == path]
        if not routes:
            raise RuntimeError("Combined peak reset route missing: " + path)
        app.router.routes.remove(routes[-1])
        app.router.routes.insert(0, routes[-1])
    return {"installed": True, "version": VERSION,
            "route_priority": 0, "scope": "REPORTING_ONLY_COMBINED_LIVE_OPEN_PNL"}


