"""Authenticated XAG-only harvest HWM reset; leaves live trades and entry policy intact."""
from __future__ import annotations

import hmac
import threading
from datetime import datetime, timezone
from typing import Any, Dict, Optional

from fastapi import Header, HTTPException, Request

import metals_xag_live_harvest as harvest

VERSION = "metals_xag_manual_highwater_reset_v1_2026_11_24"
PREVIEW_ROUTE = "/api/live-xag-harvest-reset/preview"
RESET_ROUTE = "/api/live-xag-harvest-reset/reset"
_LOCK = threading.RLock()
_INSTALLED = False


def _proof(core: Any) -> Dict[str, Any]:
    snapshot = harvest._live_snapshot(core)
    if not snapshot.get("ok"):
        return {"ok": False, "reason": snapshot.get("reason") or "xag_live_snapshot_unavailable"}
    state = harvest._get_state(core)
    cycle = str(state.get("cycle_id") or "")
    if not cycle:
        return {"ok": False, "reason": "xag_harvest_cycle_unavailable"}
    if int(snapshot.get("count") or 0) < 1:
        return {"ok": False, "reason": "xag_live_basket_is_flat"}
    stages = harvest._stages(core, cycle)
    unresolved = [
        stage for stage in stages
        if str(stage.get("status") or "").upper() in {"EXECUTING", "REVIEW_REQUIRED"}
        or (
            (_num(stage.get("executed_bank_gbp")) or 0.0) > 0
            and str(stage.get("status") or "").upper() != "EXECUTED"
        )
    ]
    if unresolved:
        return {
            "ok": False, "reason": "xag_harvest_stage_requires_review",
            "unresolved_stage_count": len(unresolved),
        }
    current_r = float(snapshot["current_r"])
    current_gbp = float(snapshot["current_gbp"])
    return {
        "ok": True, "cycle_id": cycle, "open_count": int(snapshot["count"]),
        "broker_trade_ids": sorted(str(row["id"]) for row in snapshot["rows"]),
        "current_r": round(current_r, 8), "current_gbp": round(current_gbp, 6),
        "new_hwm_r": max(0.0, round(current_r, 8)),
        "new_hwm_gbp": max(0.0, round(current_gbp, 6)),
        "previous_hwm_r": float(state.get("high_water_r") or 0.0),
        "previous_hwm_gbp": float(state.get("high_water_gbp") or 0.0),
        "next_harvest_threshold_r": 30,
        "reconciliation_exact": True,
        "unresolved_entry_intents": False,
        "scope": "LIVE_XAG_SHORT_ONLY",
    }


def _num(value: Any) -> Optional[float]:
    try:
        n = float(value)
        return n if n == n and abs(n) != float("inf") else None
    except (TypeError, ValueError):
        return None


def _preview(core: Any) -> Dict[str, Any]:
    proof = _proof(core)
    return {
        "ok": True, "allowed": bool(proof.get("ok")),
        "baseline": proof if proof.get("ok") else None,
        "blockers": [] if proof.get("ok") else [proof.get("reason") or "xag_reset_unavailable"],
        "preserves_open_positions": True, "preserves_entry_rules_and_sizing": True,
        "preserves_xau_state": True, "version": VERSION,
    }


def _perform_reset(core: Any, expected_cycle: str, expected_ids: list[str]) -> Dict[str, Any]:
    # Use the exact same session-level advisory lock as the live harvest worker.
    # This prevents a harvest tick from planning or submitting a close mid-reset.
    with core.get_conn() as guard:
        lock = guard.execute("SELECT pg_try_advisory_lock(2026112030) AS acquired").fetchone()
        if not lock or not lock["acquired"]:
            return {"ok": False, "reason": "xag_harvest_worker_busy"}
        try:
            proof = _proof(core)
            if not proof.get("ok"):
                return proof
            if (proof["cycle_id"] != expected_cycle
                    or proof["broker_trade_ids"] != sorted(expected_ids)):
                return {"ok": False, "reason": "xag_basket_changed_since_preview"}
            now = datetime.now(timezone.utc).isoformat()
            new_cycle = "XAG_LIVE_RESET_" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
            with core.get_conn() as conn:
                conn.execute("""CREATE TABLE IF NOT EXISTS metals_xag_live_harvest_resets(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at_utc TEXT NOT NULL, old_cycle_id TEXT NOT NULL,
                    new_cycle_id TEXT NOT NULL, previous_hwm_r REAL NOT NULL,
                    previous_hwm_gbp REAL NOT NULL, new_hwm_r REAL NOT NULL,
                    new_hwm_gbp REAL NOT NULL, current_r REAL NOT NULL,
                    current_gbp REAL NOT NULL, open_count INTEGER NOT NULL,
                    broker_trade_ids_json TEXT NOT NULL)""")
                # Archive only stages that did not execute. Executed stage records
                # remain immutable in their original cycle for audit/history.
                conn.execute("""UPDATE metals_xag_live_harvest_stages SET
                    status='MANUAL_HWM_ARCHIVED', updated_at_utc=?,
                    reason=COALESCE(reason,'') || ' | archived with manual XAG HWM reset'
                    WHERE cycle_id=? AND status NOT IN
                    ('EXECUTED','EXPIRED_FLAT','LEGACY_PASSED_UNBANKED','MANUAL_HWM_ARCHIVED')""",
                    (now, expected_cycle))
                conn.execute("""UPDATE metals_xag_live_harvest_state
                    SET cycle_id=?, high_water_r=?, high_water_gbp=?, updated_at_utc=?
                    WHERE id=1""",
                    (new_cycle, proof["new_hwm_r"], proof["new_hwm_gbp"], now))
                conn.execute("""INSERT INTO metals_xag_live_harvest_resets
                    (created_at_utc,old_cycle_id,new_cycle_id,previous_hwm_r,
                     previous_hwm_gbp,new_hwm_r,new_hwm_gbp,current_r,current_gbp,
                     open_count,broker_trade_ids_json)
                    VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                    (now, expected_cycle, new_cycle, proof["previous_hwm_r"],
                     proof["previous_hwm_gbp"], proof["new_hwm_r"],
                     proof["new_hwm_gbp"], proof["current_r"], proof["current_gbp"],
                     proof["open_count"], __import__("json").dumps(proof["broker_trade_ids"])))
                conn.commit()
            return {
                "ok": True, "status": "XAG_HIGHWATER_ONLY_RESET",
                "previous_hwm_r": proof["previous_hwm_r"],
                "previous_hwm_gbp": proof["previous_hwm_gbp"],
                "new_hwm_r": proof["new_hwm_r"], "new_hwm_gbp": proof["new_hwm_gbp"],
                "current_r": proof["current_r"], "current_gbp": proof["current_gbp"],
                "open_count": proof["open_count"], "new_cycle_id": new_cycle,
                "next_harvest_threshold_r": 30,
                "broker_orders_sent": False, "open_positions_and_stops_unchanged": True,
                "entry_rules_and_sizing_unchanged": True, "xau_unchanged": True,
            }
        finally:
            guard.execute("SELECT pg_advisory_unlock(2026112030)")


def install(core: Any, app: Any) -> Dict[str, Any]:
    global _INSTALLED
    if _INSTALLED:
        return {"installed": True, "version": VERSION}
    harvest._init(core)

    def preview() -> Dict[str, Any]:
        return _preview(core)

    async def reset(request: Request, x_webhook_secret: Optional[str] = Header(default=None)) -> Dict[str, Any]:
        expected = str(getattr(core, "WEBHOOK_SECRET", "") or "")
        if not expected or not x_webhook_secret or not hmac.compare_digest(str(x_webhook_secret), expected):
            raise HTTPException(status_code=401, detail="Invalid WEBHOOK_SECRET")
        try:
            body = await request.json()
        except Exception:
            raise HTTPException(status_code=400, detail="Invalid JSON")
        if (not isinstance(body, dict)
                or body.get("confirm") != "RESET_XAG_HIGHWATER_ONLY"
                or body.get("acknowledge_current_basket") is not True):
            raise HTTPException(status_code=400, detail="Explicit high-water-only confirmation and basket acknowledgement required")
        check = _preview(core)
        if not check.get("allowed"):
            raise HTTPException(status_code=409, detail={
                "reason": "xag_highwater_only_reset_blocked",
                "blockers": check.get("blockers", []),
            })
        baseline = check["baseline"]
        with _LOCK:
            outcome = _perform_reset(
                core, str(baseline["cycle_id"]), list(baseline["broker_trade_ids"])
            )
        if not outcome.get("ok"):
            raise HTTPException(status_code=409, detail=outcome)
        return outcome

    app.add_api_route(PREVIEW_ROUTE, preview, methods=["GET"], include_in_schema=False)
    app.add_api_route(RESET_ROUTE, reset, methods=["POST"], include_in_schema=False)
    for path in (PREVIEW_ROUTE, RESET_ROUTE):
        matches = [route for route in app.router.routes if getattr(route, "path", "") == path]
        if not matches:
            raise RuntimeError("XAG HWM reset route missing: " + path)
        app.router.routes.remove(matches[-1])
        app.router.routes.insert(0, matches[-1])
    _INSTALLED = True
    return {"installed": True, "version": VERSION, "scope": "LIVE_XAG_SHORT_ONLY",
            "positions_unchanged": True, "entry_rules_unchanged": True}


