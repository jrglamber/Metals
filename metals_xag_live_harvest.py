"""LIVE XAG SHORT basket harvest, independently broker-authoritative.

Copies the LIVE XAU harvest ladder: 30R, then +50R; banks approximately
20%, 20%, then 25% of the profitable open-trade pool. XAG only. No writes
to XAU tables, no changes to MFE25, emergency stops, entries or sizing.
"""
from __future__ import annotations

import json
import math
import threading
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

import xag_short_live_override as xag

VERSION = "metals_xag_live_harvest_v1_2026_11_20"
FIRST_R, STEP_R = 30.0, 50.0
LOCK_KEY = 2026112030
_POLL_SECONDS = 60
_last: Dict[str, Any] = {"status": "NOT_STARTED"}
_thread = None


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _f(value: Any) -> Optional[float]:
    if value is None or isinstance(value, bool):
        return None
    try:
        v = float(value)
        return v if math.isfinite(v) else None
    except (ValueError, TypeError):
        return None


def _fraction(level: float) -> float:
    return 0.20 if level <= 80.000001 else 0.25


def _next_level(executed: List[float]) -> float:
    return FIRST_R if not executed else max(executed) + STEP_R


def _init(core: Any) -> None:
    with core.get_conn() as conn:
        conn.execute("""CREATE TABLE IF NOT EXISTS metals_xag_live_harvest_state(
            id INTEGER PRIMARY KEY, cycle_id TEXT NOT NULL,
            high_water_r REAL NOT NULL, high_water_gbp REAL NOT NULL,
            updated_at_utc TEXT NOT NULL)""")
        conn.execute("""CREATE TABLE IF NOT EXISTS metals_xag_live_harvest_stages(
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cycle_id TEXT NOT NULL, threshold_r REAL NOT NULL,
            bank_fraction REAL NOT NULL, status TEXT NOT NULL,
            created_at_utc TEXT NOT NULL, updated_at_utc TEXT NOT NULL,
            executed_at_utc TEXT,
            trigger_current_r REAL NOT NULL, trigger_current_gbp REAL NOT NULL,
            trigger_profitable_pool_gbp REAL NOT NULL, target_bank_gbp REAL NOT NULL,
            selected_json TEXT NOT NULL, executed_bank_gbp REAL NOT NULL DEFAULT 0,
            reason TEXT, UNIQUE(cycle_id,threshold_r))""")
        conn.execute("""CREATE TABLE IF NOT EXISTS metals_xag_live_harvest_events(
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            created_at_utc TEXT NOT NULL, updated_at_utc TEXT NOT NULL,
            cycle_id TEXT NOT NULL, threshold_r REAL NOT NULL,
            broker_trade_id TEXT NOT NULL, expected_gbp REAL,
            realized_gbp REAL, status TEXT NOT NULL, reason TEXT,
            UNIQUE(cycle_id,threshold_r,broker_trade_id))""")
        conn.execute("""INSERT INTO metals_xag_live_harvest_state
            (id,cycle_id,high_water_r,high_water_gbp,updated_at_utc)
            VALUES (1,'',0,0,?) ON CONFLICT (id) DO NOTHING""", (_now(),))
        conn.commit()


def _live_snapshot(core: Any) -> Dict[str, Any]:
    """Never infer 0R from a missing broker quote, risk or trade link."""
    rec = xag._reconcile(core)
    if not rec.get("ok") or not rec.get("exact_live_ownership") or rec.get("has_broker_long"):
        return {"ok": False, "reason": "xag_broker_link_reconciliation_not_exact"}
    with core.get_conn() as conn:
        intents = conn.execute("""SELECT COUNT(*) AS n
            FROM metals_xag_live_entry_intents
            WHERE status IN ('SUBMITTING','UNKNOWN_NEEDS_RECONCILIATION','OPEN_UNVERIFIED_STOP')""").fetchone()
    if int(intents["n"] or 0):
        return {"ok": False, "reason": "unresolved_live_entry_intents"}
    snap = xag._open_trades(core)
    if not snap.get("ok"):
        return {"ok": False, "reason": "broker_open_trades_unavailable"}
    broker = list(snap.get("xag") or [])
    links = xag._local_open(core)
    by_id = {str(z.get("broker_trade_id") or ""): z for z in links}
    if len(by_id) != len(links) or set(by_id) != {str(z.get("id") or "") for z in broker}:
        return {"ok": False, "reason": "xag_broker_link_ids_changed"}
    rows = []
    for t in broker:
        bid = str(t.get("id") or "")
        link = by_id[bid]
        units = _f(t.get("currentUnits"))
        pnl = _f(t.get("unrealizedPL"))
        risk = _f(link.get("estimated_risk_amount"))
        if (units is None or units >= 0 or abs(units) != xag.PILOT_UNITS
                or pnl is None or risk is None or risk <= 0
                or str(link.get("side") or "").lower() != "short"
                or str(link.get("status") or "").upper() != "OPEN"
                or not t.get("stopLossOrderID")):
            return {"ok": False, "reason": "missing_or_unverified_live_trade_risk_or_stop", "trade_id": bid}
        rows.append({"link": link, "id": bid, "pnl": pnl, "risk": risk})
    return {
        "ok": True, "rows": rows, "count": len(rows),
        "current_r": sum(z["pnl"] / z["risk"] for z in rows),
        "current_gbp": sum(z["pnl"] for z in rows),
        "profitable_pool_gbp": sum(max(z["pnl"], 0) for z in rows),
    }


def _get_state(core: Any) -> Dict[str, Any]:
    with core.get_conn() as conn:
        return dict(conn.execute(
            "SELECT * FROM metals_xag_live_harvest_state WHERE id=1").fetchone())


def _set_state(core: Any, cycle: str, high_r: float, high_gbp: float) -> None:
    with core.get_conn() as conn:
        conn.execute("""UPDATE metals_xag_live_harvest_state
            SET cycle_id=?, high_water_r=?, high_water_gbp=?, updated_at_utc=?
            WHERE id=1""", (cycle, high_r, high_gbp, _now()))
        conn.commit()


def _stages(core: Any, cycle: str) -> List[Dict[str, Any]]:
    with core.get_conn() as conn:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM metals_xag_live_harvest_stages WHERE cycle_id=? ORDER BY threshold_r",
            (cycle,)).fetchall()]


def _event(core: Any, cycle: str, level: float, bid: str) -> Optional[Dict[str, Any]]:
    with core.get_conn() as conn:
        r = conn.execute("""SELECT * FROM metals_xag_live_harvest_events
            WHERE cycle_id=? AND threshold_r=? AND broker_trade_id=?""",
            (cycle, level, bid)).fetchone()
        return dict(r) if r else None


def _record_event(core: Any, cycle: str, level: float, bid: str,
                  expected: float, status: str, realized: Optional[float] = None,
                  reason: str = "") -> None:
    with core.get_conn() as conn:
        conn.execute("""INSERT INTO metals_xag_live_harvest_events
            (created_at_utc,updated_at_utc,cycle_id,threshold_r,
            broker_trade_id,expected_gbp,realized_gbp,status,reason)
            VALUES (?,?,?,?,?,?,?,?,?)
            ON CONFLICT (cycle_id,threshold_r,broker_trade_id)
            DO UPDATE SET updated_at_utc=excluded.updated_at_utc,
                realized_gbp=excluded.realized_gbp,status=excluded.status,
                reason=excluded.reason""",
            (_now(), _now(), cycle, level, bid, expected, realized, status, reason))
        conn.commit()


def _stage_status(core: Any, stage: Dict[str, Any], status: str, total: float, reason: str) -> None:
    with core.get_conn() as conn:
        conn.execute("""UPDATE metals_xag_live_harvest_stages
            SET status=?,executed_bank_gbp=?,updated_at_utc=?,executed_at_utc=?,
                reason=? WHERE id=?""",
            (status, total, _now(), _now() if status == "EXECUTED" else None,
             reason, int(stage["id"])))
        conn.commit()


def _start_stage(core: Any, cycle: str, level: float, snapshot: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    fraction = _fraction(level)
    target = snapshot["profitable_pool_gbp"] * fraction
    winners = sorted((r for r in snapshot["rows"] if r["pnl"] > 0),
                     key=lambda r: (-r["pnl"], r["id"]))
    selected, total = [], 0.0
    for row in winners:
        if total >= target - 1e-9:
            break
        selected.append({"id": row["id"], "expected_gbp": row["pnl"]})
        total += row["pnl"]
    if target <= 0 or not selected:
        return None
    with core.get_conn() as conn:
        conn.execute("""INSERT INTO metals_xag_live_harvest_stages
            (cycle_id,threshold_r,bank_fraction,status,
            created_at_utc,updated_at_utc,trigger_current_r,trigger_current_gbp,
            trigger_profitable_pool_gbp,target_bank_gbp,selected_json,reason)
            VALUES (?,?,?,'EXECUTING',?,?,?,?,?,?,?,?)
            ON CONFLICT (cycle_id,threshold_r) DO NOTHING""",
            (cycle, level, fraction, _now(), _now(),
             snapshot["current_r"], snapshot["current_gbp"],
             snapshot["profitable_pool_gbp"], target,
             json.dumps(selected), "broker-close stage planned; separate from XAU"))
        conn.commit()
    return next((s for s in _stages(core, cycle) if float(s["threshold_r"]) == level), None)


def _execute_stage(core: Any, stage: Dict[str, Any]) -> Dict[str, Any]:
    cycle, level = stage["cycle_id"], float(stage["threshold_r"])
    selected = json.loads(stage["selected_json"])
    total = 0.0
    for pick in selected:
        bid, expected = str(pick["id"]), float(pick["expected_gbp"])
        previous = _event(core, cycle, level, bid)
        if previous and previous["status"] == "CLOSED_VERIFIED":
            total += float(previous["realized_gbp"] or 0)
            continue
        if previous and previous["status"] in {"SKIPPED_OTHER_CLOSE", "REVIEW_REQUIRED"}:
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "prior ambiguous trade close")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}

        detail = xag._request(core, f"/v3/accounts/{xag._account_id(core)}/trades/{bid}", "GET")
        t = (detail.get("data") or {}).get("trade") if detail.get("ok") else None
        t = dict(t) if isinstance(t, dict) else {}
        broker_state = str(t.get("state") or "").upper()
        if broker_state == "CLOSED":
            with core.get_conn() as conn:
                z = conn.execute(
                    "SELECT close_reason FROM metals_xag_live_trade_links WHERE broker_trade_id=?",
                    (bid,)).fetchone()
            if z and str(z["close_reason"] or "").startswith(f"LIVE_XAG_HARVEST_{int(level)}R"):
                realized = _f(t.get("realizedPL"))
                if realized is not None:
                    _record_event(core, cycle, level, bid, expected, "CLOSED_VERIFIED", realized,
                                  "broker-confirmed harvest close after recovery")
                    total += realized
                    continue
            _record_event(core, cycle, level, bid, expected, "SKIPPED_OTHER_CLOSE",
                          reason="already closed outside this harvest")
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "selected trade closed outside harvest")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        if (broker_state != "OPEN" or str(t.get("instrument") or "") != "XAG_USD"
                or _f(t.get("currentUnits")) != -xag.PILOT_UNITS
                or _f(t.get("unrealizedPL")) is None
                or float(t["unrealizedPL"]) <= 0):
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "trade no longer a verified profitable XAG Short")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        if previous and previous.get("status") == "SUBMITTING":
            # Previously ambiguous request; allow only broker-confirmed status
            # to resolve it. Never issue another close blindly.
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "ambiguous prior broker-close request")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        with core.get_conn() as conn:
            link = conn.execute(
                "SELECT * FROM metals_xag_live_trade_links WHERE broker_trade_id=? AND status='OPEN'",
                (bid,)).fetchone()
        if not link:
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "selected live link changed")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        _record_event(core, cycle, level, bid, expected, "SUBMITTING",
                      reason="durable intent before OANDA close")
        reason = f"LIVE_XAG_HARVEST_{int(level)}R"
        result = xag._close_link(core, dict(link), reason)
        if not result.get("ok") or result.get("already_closed"):
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "broker close not verified")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        realized = _f(result.get("realized_pl"))
        if realized is None:
            _stage_status(core, stage, "REVIEW_REQUIRED", total, "realized GBP not broker-verified")
            return {"status": "REVIEW_REQUIRED", "level_r": level, "banked_gbp": total}
        _record_event(core, cycle, level, bid, expected, "CLOSED_VERIFIED", realized,
                      "OANDA CLOSED confirmed by existing XAG executor")
        total += realized
    _stage_status(core, stage, "EXECUTED", total,
                  "whole-unit profitable XAG positions; OANDA close confirmed")
    return {"status": "EXECUTED", "level_r": level, "banked_gbp": round(total, 4),
            "closed_count": len(selected), "target_gbp": stage["target_bank_gbp"]}


def tick(core: Any) -> Dict[str, Any]:
    """Single active XAG harvest worker across processes, via Postgres advisory lock."""
    global _last
    result: Dict[str, Any] = {"status": "BLOCKED", "at_utc": _now()}
    try:
        with core.get_conn() as guard:
            row = guard.execute("SELECT pg_try_advisory_lock(2026112030) AS acquired").fetchone()
            if not row or not row["acquired"]:
                result.update({"status": "ALREADY_RUNNING"})
                return result
            try:
                snapshot = _live_snapshot(core)
                if not snapshot.get("ok"):
                    result["reason"] = snapshot.get("reason")
                    return result
                state = _get_state(core)
                count = snapshot["count"]
                if count == 0:
                    if state["cycle_id"]:
                        _set_state(core, "", 0.0, 0.0)
                    result.update({"status": "FLAT", "count": 0, "current_r": 0.0})
                    return result
                cycle = state["cycle_id"] or ("XAG_LIVE_" + _now().replace(":", "").replace("-", ""))
                high_r = max(float(state["high_water_r"]) if state["cycle_id"] else 0.0,
                             snapshot["current_r"])
                high_gbp = max(float(state["high_water_gbp"]) if state["cycle_id"] else 0.0,
                               snapshot["current_gbp"])
                _set_state(core, cycle, high_r, high_gbp)
                result.update({"status": "MONITORING", "cycle_id": cycle,
                               "count": count, "current_r": round(snapshot["current_r"], 4),
                               "high_water_r": round(high_r, 4),
                               "current_gbp": round(snapshot["current_gbp"], 2)})
                stages = _stages(core, cycle)
                pending = next((s for s in stages if s["status"] == "EXECUTING"), None)
                if any(s["status"] == "REVIEW_REQUIRED" for s in stages):
                    result.update({"status": "REVIEW_REQUIRED", "reason": "prior stage needs broker audit"})
                    return result
                if not pending:
                    executed = [float(s["threshold_r"]) for s in stages if s["status"] == "EXECUTED"]
                    next_r = _next_level(executed)
                    result["next_level_r"] = next_r
                    if snapshot["current_r"] < next_r:
                        return result
                    if not xag.config_status(core).get("management_writes_allowed"):
                        result.update({"status": "BLOCKED", "reason": "XAG management writes disabled"})
                        return result
                    pending = _start_stage(core, cycle, next_r, snapshot)
                    if pending is None:
                        result.update({"status": "BLOCKED", "reason": "no_positive_bankable_winners"})
                        return result
                out = _execute_stage(core, pending)
                result.update(out)
                return result
            finally:
                guard.execute("SELECT pg_advisory_unlock(2026112030)")
    except Exception as exc:
        result["reason"] = f"{type(exc).__name__}: {exc}"
        return result
    finally:
        _last = result


def status(core: Any) -> Dict[str, Any]:
    try:
        state = _get_state(core)
        stages = _stages(core, str(state["cycle_id"] or ""))
        return {"ok": True, "version": VERSION, "scope": "LIVE_XAG_SHORT_ONLY",
                "ladder_r": [30, 80, 130, 180, 230, 280],
                "fractions": [0.20, 0.20, 0.25],
                "cycle": state, "stages": stages[-10:], "last_tick": dict(_last),
                "xau_unchanged": True, "entry_sizing_unchanged": True}
    except Exception as exc:
        return {"ok": False, "reason": f"{type(exc).__name__}: {exc}"}


def install(core: Any, app: Any) -> Dict[str, Any]:
    global _thread
    _init(core)
    @app.get("/api/live-xag-harvest-ladder-view")
    def harvest_view() -> Dict[str, Any]:
        return status(core)
    routes = [r for r in app.router.routes if getattr(r, "path", "") == "/api/live-xag-harvest-ladder-view"]
    if not routes:
        raise RuntimeError("XAG harvest status route absent")
    app.router.routes.remove(routes[-1])
    app.router.routes.insert(0, routes[-1])
    def loop() -> None:
        while True:
            out = tick(core)
            if out.get("status") != "MONITORING" or out.get("count") == 0:
                print("METALS_XAG_LIVE_HARVEST " + json.dumps(out, default=str), flush=True)
            threading.Event().wait(_POLL_SECONDS)
    _thread = threading.Thread(target=loop, daemon=True, name="xag-live-harvest")
    _thread.start()
    return {"installed": True, "version": VERSION, "scope": "LIVE_XAG_SHORT_ONLY",
            "broker_hosted_closures": True, "separate_ladder": True, "poll_seconds": _POLL_SECONDS}
